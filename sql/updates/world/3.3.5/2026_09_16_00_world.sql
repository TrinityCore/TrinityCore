    `creature_entry` INT UNSIGNED NOT NULL,
    `world_faction_id` INT UNSIGNED NOT NULL,
    PRIMARY KEY (`creature_entry`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8;

