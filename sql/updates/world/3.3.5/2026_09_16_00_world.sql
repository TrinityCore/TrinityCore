-- README.md). Generated from data/elwynn/factions/world_faction_assignments.csv
-- (world_faction column) joined against data/elwynn/factions/world_factions.csv
-- (key -> world_faction_id) - the versioned, reviewed source of truth for
-- these 182 permanent Elwynn creature template assignments. Do not hand-edit
-- this table's content; regenerate it from those CSVs if the assignments
-- change.
--
-- Not a Faction.dbc/FactionTemplate.dbc table - see that README for the
-- AI WorldFactionId / TrinityCore Faction split this data layer preserves.
-- WorldFactionCatalog::Resolve() (src/server/game/AIWorld/Faction/) falls
-- back to 0 (Unaffiliated) for any creature_entry not present here, so an
-- explicit world_faction_id = 0 row below (NEUTRAL_UNAFFILIATED) is
-- functionally redundant with that fallback - included anyway so every one
-- of the 182 accepted template assignments has an explicit, auditable row,
-- matching world_faction_assignments.csv's own row count.
